function extractJson(text) {
  if (!text) return null;
  const cleaned = text.replace(/```json/gi, "").replace(/```/g, "").trim();
  try {
    return JSON.parse(cleaned);
  } catch {
    const match = cleaned.match(/\{[\s\S]*\}/);
    if (match) {
      try {
        return JSON.parse(match[0]);
      } catch {
        return null;
      }
    }
    return null;
  }
}

// Согласование КБЖУ по правилу Атуотера: 1 г белка/углеводов = 4 ккал, 1 г жира = 9 ккал.
// Страхует от случаев, когда модель вернула калории, не бьющиеся с макросами.
function reconcileMacros(dish) {
  const implied = dish.protein * 4 + dish.carbs * 4 + dish.fat * 9;
  if (implied <= 0) return dish; // нет макросов — доверяем калориям как есть
  if (dish.calories <= 0) {
    dish.calories = Math.round(implied);
    return dish;
  }
  const diff = Math.abs(dish.calories - implied) / implied;
  if (diff > 0.2) {
    // Калории сильно расходятся с макросами — доверяем макросам и снижаем уверенность.
    dish.calories = Math.round(implied);
    if (dish.confidence === "high") dish.confidence = "medium";
  }
  return dish;
}

// Названия, которые модель выдаёт, когда НЕ опознала еду. Считаем их признаком неуверенности,
// даже если сама модель поставила "high".
const GENERIC_NAMES = new Set(["блюдо", "блюда", "еда", "продукт", "перекус", "обед", "ужин", "завтрак"]);

// Итоговая уверенность решается проверяемыми признаками, а не словом модели.
// Причина: на боевых данных Gemini ставил "high" в 64% случаев и "low" не поставил ни разу,
// из-за чего в клиенте перестала показываться плашка «AI не уверен — проверьте запись».
// Арифметика соврать не может, самооценка модели — может.
function calibrateConfidence(dish, declared) {
  const w = dish.weight_grams;
  const kcal = dish.calories;
  const implied = dish.protein * 4 + dish.carbs * 4 + dish.fat * 9;
  const density = w > 0 ? kcal / w : null;

  // Проверять нечего или числа невозможны физически — предупреждаем всегда.
  if (w <= 0 || kcal <= 0) return "low";
  if (density > 9 || density < 0.2) return "low"; // плотнее чистого жира / жиже бульона
  if (implied > 0 && Math.abs(kcal - implied) / implied > 0.3) return "low";
  if (GENERIC_NAMES.has(dish.dish_name.trim().toLowerCase())) return "low"; // еду не опознали

  // Признаки оценки «на глазок»: подозрительно круглый вес и нетипичная плотность.
  const roundWeight = w >= 100 && w % 50 === 0;
  const oddDensity = density < 0.5 || density > 5;
  if (roundWeight && oddDensity) return "low";          // оба сразу — числу верить нельзя
  if (declared === "high" && (roundWeight || oddDensity)) return "medium"; // «high» не заслужен
  return declared;
}

function normalizeDish(d) {
  const dish = {
    dish_name: d.dish_name || d.name || "Блюдо",
    calories: Math.round(Number(d.calories) || 0),
    protein: Math.round((Number(d.protein) || 0) * 10) / 10,
    fat: Math.round((Number(d.fat) || 0) * 10) / 10,
    carbs: Math.round((Number(d.carbs) || 0) * 10) / 10,
    weight_grams: Math.round(Number(d.weight_grams) || 0),
    confidence: ["high", "medium", "low"].includes(d.confidence) ? d.confidence : "medium"
  };
  const reconciled = reconcileMacros(dish);
  // Числа не трогаем (их правит только Атуотер выше) — пересчитываем лишь уверенность.
  reconciled.confidence = calibrateConfidence(reconciled, reconciled.confidence);
  return reconciled;
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// Общий бюджет времени на ОДИН скан — на всю цепочку провайдеров вместе.
// Без него арифметика была такая: 3 провайдера × 2 попытки разбора × 3 ретрая × 60 с
// таймаута = до девяти минут на один запрос. Пользователь всё это время видел вечную
// загрузку, отваливался по своему таймауту и жал «Сканировать» ещё раз, плодя такие же
// девятиминутные задачи.
//
// Но 30 секунд оказались слишком жёстким сроком. Сразу после массовой рассылки
// сотни людей сканируют одновременно, очередь к Gemini растёт, и скан не успевал
// в бюджет — человек получал «не удалось распознать» вместо еды. Подождать лишние
// полминуты (честно предупредив об этом в приложении) куда лучше, чем не ответить
// вовсе, поэтому бюджет поднят до 70 с — с запасом под таймаут клиента (90 с).
const AI_TOTAL_BUDGET_MS = Number(process.env.AI_TOTAL_BUDGET_MS || 70000);
const AI_CALL_TIMEOUT_MS = Number(process.env.AI_CALL_TIMEOUT_MS || 25000);
// Минимум остатка, при котором вызов вообще имеет смысл. Без него в самом конце
// бюджета уходил заведомо провальный запрос с таймаутом в полторы секунды: ответить
// за это время не успевал никто, зато именно его ошибка («timeout of 1422ms exceeded»)
// уезжала в канал и прятала настоящую причину сбоя.
const AI_MIN_CALL_MS = Number(process.env.AI_MIN_CALL_MS || 6000);

const GEMINI_MAX_RPM = Number(process.env.GEMINI_MAX_RPM || 14);
const GEMINI_MIN_INTERVAL_MS = Math.ceil(60000 / GEMINI_MAX_RPM);
const geminiNextStartAt = new Map();
function budgetLeft(deadline) {
  return deadline ? deadline - Date.now() : AI_CALL_TIMEOUT_MS;
}

function deadlineError(model) {
  const err = new Error("ai_deadline_exceeded");
  err.status = 504;
  err.model = model;
  return err;
}

async function waitForGeminiSlot(model, deadline) {
  const now = Date.now();
  const nextStartAt = Math.max(now, geminiNextStartAt.get(model) || now);
  const waitMs = nextStartAt - now;
  if (deadline && waitMs >= Math.max(0, budgetLeft(deadline) - AI_MIN_CALL_MS)) {
    throw deadlineError(model);
  }
  geminiNextStartAt.set(model, nextStartAt + GEMINI_MIN_INTERVAL_MS);
  if (waitMs > 0) await sleep(waitMs);
}

// hasNext — есть ли в цепочке следующий провайдер. Если есть, на 429 (кончилась квота)
// не ретраим: Gemini просит ждать до минуты, а держать пользователя столько нельзя —
// быстрее молча уйти к следующему провайдеру.
// deadline — общий срок на весь скан (мс, Date.now()-шкала); за него не выходим.
async function callProvider(provider, messages, maxTokens, hasNext = false, deadline = null) {
  if (!provider.apiKey) {
    const err = new Error(`${provider.name}_not_configured`);
    err.status = 503;
    err.model = provider.model;
    throw err;
  }
  // Ретраи разовых сбоев: сеть / 5xx / 429 (rate limit) — до 3 попыток с нарастающей паузой.
  // Из-за них раньше в логах появлялись «Request failed with status code 500».
  let lastErr;
  for (let attempt = 0; attempt < 3; attempt++) {
    if (provider.name === "gemini") await waitForGeminiSlot(provider.model, deadline);
    const left = budgetLeft(deadline);
    if (left <= AI_MIN_CALL_MS) throw lastErr || deadlineError(provider.model);
    try {
      const { data } = await axios.post(
        provider.url,
        { model: provider.model, messages, max_tokens: maxTokens, temperature: 0.2, response_format: { type: "json_object" } },
        {
          headers: { Authorization: `Bearer ${provider.apiKey}`, "Content-Type": "application/json" },
          // Таймаут одного вызова не может быть больше остатка общего бюджета.
          timeout: Math.min(AI_CALL_TIMEOUT_MS, left)
        }
      );
      return data;
    } catch (err) {
      err.model = provider.model;
      err.provider = provider.name;
      lastErr = err;
      const status = err.response?.status;
      if (hasNext && (status === 429 || status >= 500)) break;
      // Таймаут ПЛАТНОГО провайдера не ретраим: запрос на его стороне уже выполнен
      // и оплачен, повтор просто покупает тот же ответ второй раз.
      const timedOut = err.code === "ECONNABORTED" || /timeout/i.test(err.message || "");
      if (timedOut && (provider.name === "openai" || hasNext)) break;
      const retryable = !err.response || status >= 500 || status === 429;
      if (!retryable || attempt === 2) break;
      await sleep(400 * (attempt + 1));
    }
  }
  throw lastErr;
}

// Достаёт блюда из ответа модели, ВКЛЮЧАЯ обрезанный/битый JSON.
// 1) пробуем разобрать весь ответ; 2) если не вышло — вытаскиваем отдельные завершённые
// объекты блюд {...} (плоские, без вложенных скобок) — так уцелевшие блюда не теряются,
// даже если массив оборвался на середине из-за лимита токенов. Возвращает массив (возможно пустой).
function parseDishes(content) {
  if (!content) return [];
  const full = extractJson(content);
  if (full && Array.isArray(full.dishes) && full.dishes.length) {
    return full.dishes.map(normalizeDish);
  }
  const objs = content.match(/\{[^{}]*\}/g) || [];
  const dishes = [];
  for (const o of objs) {
    try {
      const d = JSON.parse(o);
      if (d && (d.dish_name || d.name) && (d.calories != null || d.protein != null)) {
        dishes.push(normalizeDish(d));
      }
    } catch { /* не блюдо — пропускаем */ }
  }
  return dishes;
}

// Запасное блюдо: создаётся, когда модель так и не вернула результат — чтобы еда добавлялась ВСЕГДА.
// Низкая уверенность подсветит в клиенте «проверьте запись», пользователь поправит числа.
function fallbackDish(name) {
  return normalizeDish({
    dish_name: (name && String(name).trim().slice(0, 80)) || "Блюдо",
    calories: 0, protein: 0, fat: 0, carbs: 0, weight_grams: 0, confidence: "low"
  });
}

// Складываем расход двух вызовов (основного и починки), иначе учёт стоимости занижен:
// раньше usage перезаписывался ответом повтора, и первый — самый дорогой — вызов пропадал
// из ai_usage вместе со своей ценой.
function addUsage(a, b) {
  if (!b) return a;
  return {
    prompt_tokens: (a.prompt_tokens || 0) + (b.prompt_tokens || 0),
    completion_tokens: (a.completion_tokens || 0) + (b.completion_tokens || 0),
    total_tokens: (a.total_tokens || 0) + (b.total_tokens || 0),
    // cached_tokens лежит внутри prompt_tokens_details и участвует в расчёте цены.
    prompt_tokens_details: {
      cached_tokens:
        (a.prompt_tokens_details?.cached_tokens || 0) + (b.prompt_tokens_details?.cached_tokens || 0)
    }
  };
}

// Один провайдер: вызов → разбор → починка ответа.
// dishes пустой, если модель так и не вернула ни одного блюда.
async function analyzeWith(provider, buildMessages, maxTokens, hasNext, deadline) {
  let usage = { prompt_tokens: 0, completion_tokens: 0, total_tokens: 0 };
  const msgs = buildMessages(provider.prompt());

  const data = await callProvider(provider, msgs, maxTokens, hasNext, deadline);
  const choice = data.choices?.[0] || {};
  const content = choice.message?.content || "";
  const finishReason = choice.finish_reason || null;
  usage = addUsage(usage, data.usage);

  let dishes = parseDishes(content);
  if (dishes.length) {
    return {
      dishes, low_confidence: dishes.some((d) => d.confidence === "low"),
      usage, model: provider.model, finish_reason: finishReason, fallback: false
    };
  }

  // Блюд не нашлось. Раньше повтор пересылал ИСХОДНЫЕ сообщения целиком — вместе с
  // base64-картинкой и полным промптом, — то есть стоил столько же, сколько первый вызов,
  // а при finish_reason="length" ещё и удваивал max_tokens поверх уже оплаченных токенов.
  // Теперь повтор — это ПОЧИНКА ФОРМАТА: отправляем только сам неразобранный ответ и просим
  // переписать его валидным JSON. Картинки в нём нет, поэтому он дешевле в разы.
  const raw = content.trim();
  if (!raw) {
    // Модель не сказала вообще ничего — чинить нечего, пусть отвечает следующий провайдер.
    return { dishes: [], usage, model: provider.model, finish_reason: finishReason };
  }
  if (budgetLeft(deadline) <= AI_MIN_CALL_MS) {
    return { dishes: [], usage, model: provider.model, finish_reason: finishReason };
  }

  try {
    const repair = await callProvider(
      provider,
      [{
        role: "user",
        content:
          'Ниже — ответ, который не удалось разобрать. Перепиши его СТРОГО как JSON вида ' +
          '{"dishes":[{"dish_name":"","calories":0,"protein":0,"fat":0,"carbs":0,"weight_grams":0,"confidence":"low"}]} ' +
          'минимум с ОДНИМ блюдом. Ничего не досчитывай и не выдумывай — только приведи к формату ' +
          'то, что уже есть. Пустой массив не возвращай.\n\n' + raw.slice(0, 4000)
      }],
      // Починке форматирования много места не нужно.
      Math.min(maxTokens, 1200),
      hasNext,
      deadline
    );
    usage = addUsage(usage, repair.usage);
    dishes = parseDishes(repair.choices?.[0]?.message?.content || "");
    if (dishes.length) {
      return {
        dishes, low_confidence: true,
        usage, model: provider.model, finish_reason: finishReason, fallback: true
      };
    }
  } catch (e) {
    // Починка — необязательный шаг: не вышло, значит идём к следующему провайдеру.
    console.error(`[ai] починка ответа ${provider.model} не удалась: ${e.message}`);
  }

  return { dishes: [], usage, model: provider.model, finish_reason: finishReason };
}

// Как провайдер называется в отчёте об ошибке — по-человечески, а не именем переменной.
function providerLabel(provider) {
  const m = String(provider.model || "?");
  return provider.name === "gemini" ? `Gemini ${m.replace(/^gemini-/, "")}` : `OpenAI ${m}`;
}

// Почему конкретный провайдер не справился — одной понятной фразой.
function describeFailure(err) {
  const status = err.response?.status;
  if (err.message === "ai_deadline_exceeded") return "не успевал в оставшееся время — пропустили";
  if (/_not_configured$/.test(err.message || "")) return "не настроен (нет ключа)";
  if (err.code === "ECONNABORTED" || /timeout/i.test(err.message || "")) return "не ответил вовремя";
  if (status === 429) return "упёрся в лимит запросов (429)";
  if (status >= 500) return `сбой на стороне провайдера (${status})`;
  if (status) return `ответил ошибкой ${status}`;
  return err.message || "неизвестная ошибка";
}

// Разбор цепочки для канала: кого спрашивали, сколько ждали и на чём встали.
// Раньше в канал уезжала ПОСЛЕДНЯЯ ошибка — почти всегда обрубок бюджета вроде
// «timeout of 1422ms exceeded», по которому нельзя понять вообще ничего: настоящая
// причина случилась двумя провайдерами раньше.
function chainDetail(trace, totalMs, skipped) {
  const total = trace.length + skipped;
  const head = `ни одна из ${total} моделей не ответила за ${(totalMs / 1000).toFixed(1)} с`;
  const lines = trace.map((t, i) => `  ${i + 1}) ${t.label} — ${(t.ms / 1000).toFixed(1)} с, ${t.outcome}`);
  if (skipped > 0) lines.push(`  + ещё ${skipped} не спрашивали: время вышло`);
  return `${head}\n${lines.join("\n")}`;
}

// Идём по цепочке: побеждает первый провайдер, вернувший блюда.
// Упал или отдал пустоту — молча берём следующего. Всегда возвращает непустой
// { dishes, low_confidence, usage, model, finish_reason, fallback } либо кидает ошибку,
// если не ответил ВООБЩЕ никто (тогда роут отдаст ai_failed, как и раньше).
async function analyze({ providers, buildMessages, maxTokens, fallbackName }) {
  let firstErr = null;
  let lastErr = null;
  let lastEmpty = null;
  // Один срок на всю цепочку: провайдеров несколько, а ждёт пользователь один раз.
  const deadline = Date.now() + AI_TOTAL_BUDGET_MS;
  const startedAt = Date.now();
  // Трасса цепочки — чтобы в канал уехал разбор, а не огрызок последней ошибки.
  const trace = [];
  let skipped = 0;
  // Платим за КАЖДУЮ попытку, а не только за победившую, поэтому расход копим по всем.
  let spent = { prompt_tokens: 0, completion_tokens: 0, total_tokens: 0 };

  for (let i = 0; i < providers.length; i++) {
    const provider = providers[i];
    const hasNext = i < providers.length - 1;
    if (budgetLeft(deadline) <= AI_MIN_CALL_MS) {
      skipped = providers.length - i;
      console.error("[ai] бюджет времени на скан исчерпан — обрываю цепочку провайдеров");
      break;
    }
    const attemptAt = Date.now();
    try {
      const result = await analyzeWith(provider, buildMessages, maxTokens, hasNext, deadline);
      spent = addUsage(spent, result.usage);
      if (result.dishes.length) return { ...result, usage: spent };
      trace.push({ label: providerLabel(provider), ms: Date.now() - attemptAt, outcome: "ответил, но блюд не нашёл" });
      lastEmpty = result;
    } catch (err) {
      if (!firstErr) firstErr = err;
      lastErr = err;
      trace.push({ label: providerLabel(provider), ms: Date.now() - attemptAt, outcome: describeFailure(err) });
      if (err.usage) spent = addUsage(spent, err.usage);
      console.error(`[ai] ${provider.name}/${provider.model} не справился: ${err.message} — пробую следующего`);
    }
  }

  // Все провайдеры упали с ошибкой и никто даже не ответил — это ошибка, а не «не распознал».
  // Наверх отдаём ПЕРВУЮ ошибку цепочки: именно она запустила лавину, а последняя —
  // как правило лишь её следствие (последнему провайдеру достался огрызок бюджета).
  if (!lastEmpty && (firstErr || lastErr)) {
    const err = firstErr || lastErr;
    err.usage = spent;
    err.detail = chainDetail(trace, Date.now() - startedAt, skipped);
    throw err;
  }
  // Никто не ответил и ошибки нет — значит вышел бюджет времени.
  if (!lastEmpty) {
    const err = deadlineError(providers[providers.length - 1]?.model);
    err.usage = spent;
    err.detail = chainDetail(trace, Date.now() - startedAt, skipped);
    throw err;
  }

  // Кто-то ответил, но блюд не нашёл. Запас: еда добавляется всегда (с пометкой низкой уверенности).
  return {
    dishes: [fallbackDish(fallbackName)],
    low_confidence: true,
    usage: spent,
    model: lastEmpty.model,
    finish_reason: lastEmpty.finish_reason,
    fallback: true
  };
}

// Возвращает { dishes, low_confidence, usage, model, finish_reason, fallback }
async function analyzeImage(imageBuffer, mimeType = "image/jpeg") {
  const dataUrl = `data:${mimeType};base64,${imageBuffer.toString("base64")}`;
  return analyze({
    providers: visionChain(),
    buildMessages: (prompt) => [
      {
        role: "user",
        content: [
          { type: "text", text: prompt },
          { type: "image_url", image_url: { url: dataUrl, detail: "high" } }
        ]
      }
    ],
    maxTokens: 3000,
    fallbackName: "Блюдо"
  });
}

// Возвращает { dishes, low_confidence, usage, model, finish_reason, fallback }
async function analyzeText(description) {
  const text = String(description || "").slice(0, 500);
  return analyze({
    providers: textChain(),
    buildMessages: (prompt) => [
      { role: "system", content: prompt },
      { role: "user", content: text }
    ],
    maxTokens: 1500,
    fallbackName: text // не распозналось — берём описание пользователя как название
  });
}

