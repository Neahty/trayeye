async function loadAll() {
  if (cache && Date.now() - cacheAt < CACHE_TTL) return cache;
  const map = { ...DEFAULTS };
  try {
    const { rows } = await db.query("SELECT key, value FROM app_settings");
    for (const r of rows) map[r.key] = r.value;
  } catch (err) {
    // таблицы может не быть до миграции — отдаём дефолты
    console.warn("[settings] load failed, using defaults:", err.message);
  }
  cache = map;
  cacheAt = Date.now();
  return map;
}

async function get(key) {
  const all = await loadAll();
  return all[key];
}

async function getMany(keys) {
  const all = await loadAll();
  const out = {};
  for (const k of keys) out[k] = all[k];
  return out;
}

async function set(key, value, updatedBy = null) {
  await db.query(
    `INSERT INTO app_settings (key, value, updated_at, updated_by)
     VALUES ($1, $2, NOW(), $3)
     ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value, updated_at = NOW(), updated_by = EXCLUDED.updated_by`,
    [key, JSON.stringify(value), updatedBy]
  );
  invalidate();
}

function invalidate() {
  cache = null;
  cacheAt = 0;
}

module.exports = { get, getMany, set, loadAll, invalidate, DEFAULTS };
