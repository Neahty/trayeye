// Открытие внешних ссылок из приложения.
// В отличие от мини-аппа в Telegram, здесь нет ни openTelegramLink, ни openLink:
// ссылку отдаём системе, и iOS сам решает, чем её открыть — t.me уйдёт в Telegram,
// если он установлен, остальное в Safari.
export function openTgLink(url) {
  if (!url) return;
  window.open(url, "_blank", "noopener");
}

// Открытие окна оплаты ЮKassa.
// Внутри webview приложения диплинки в банки (tinkoff://, bank1000...://) не работают —
// поэтому оплату уводим в системный браузер, оттуда банк подхватывается штатно.
// Шторка с кнопкой — запасной путь: если автозапуск браузера не сработал,
// пользователь открывает оплату сам, прямым нажатием.
export function openPayment(ui, url) {
  if (!url) return;
  openTgLink(url);
  ui.sheet({
    type: "info",
    title: "Оплата открыта в браузере",
    body: "Завершите оплату и вернитесь сюда — подписка активируется автоматически. Если браузер не открылся, нажмите кнопку ниже.",
    actionLabel: "Открыть оплату",
    onAction: () => openTgLink(url)
  });
}
